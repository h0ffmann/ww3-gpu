#!/usr/bin/env python3
"""bench_dia_record: the medians of scripts/bench_dia.sh as two records of bench/results/.

    bench_dia_record.py <results.tsv> --regtest "passed: <command>" --points N --calls N --runs N
                        --switch "<switch>" [--kernel-only 0|1]

Writes dia-cpu-kernel-<date>.json and, unless --kernel-only 1, dia-cpu-model-<date>.json; their
tables are generated by `scripts/results.py table` into the pages that carry their markers.
"""
import argparse
import datetime as dt
import json
import pathlib
import platform
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "bench" / "results"
GRIDS = {"ww3_ts1": "ww3_ts1 grid (NK=36, NTH=24)", "bench_small": "bench_small grid (NK=24, NTH=24)"}


def sh(*cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def machine():
    model = ""
    for line in sh("lscpu").splitlines():
        if line.startswith("Model name:"):
            model = line.split(":", 1)[1].strip()
    return f"{model or platform.processor()} ({sh('nproc', '--all')} hardware threads), CPU only"


def rows(tsv):
    lines = pathlib.Path(tsv).read_text(encoding="utf-8").splitlines()
    head = lines[0].split("\t")
    return [dict(zip(head, ln.split("\t"))) for ln in lines[1:] if ln.strip()]


def label(threads):
    return "Serial (1 thread)" if threads == "1" else f"OpenMP, {threads} threads"


def ratio(a, b):
    return f"{float(a) / float(b):.2f}x" if float(b) > 0 else "-"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv")
    ap.add_argument("--regtest", required=True)
    ap.add_argument("--points", required=True)
    ap.add_argument("--calls", required=True)
    ap.add_argument("--runs", required=True)
    ap.add_argument("--switch", required=True)
    ap.add_argument("--kernel-only", default="0")
    a = ap.parse_args(argv)
    if not a.regtest.startswith("passed"):
        print("bench_dia_record: --regtest must be 'passed: <command>'", file=sys.stderr)
        return 1
    data = rows(a.tsv)
    today = dt.date.today().isoformat()
    commit = sh("git", "-C", str(ROOT), "rev-parse", "--short", "HEAD")
    dirty = sh("git", "-C", str(ROOT), "status", "--porcelain", "--untracked-files=no")
    toolchain = (f"{sh('gfortran', '--version').splitlines()[0] if sh('gfortran', '--version') else '?'}; "
                 f"Kokkos from picasso/labs/pratico; WW3 {sh('git', '-C', str(ROOT / 'WW3'), 'rev-parse', '--short', 'HEAD')} "
                 f"built with WW3's Release flags and the switch '{a.switch}'; ww_kokkos -ffp-contract=off; "
                 "v1 -O3 -march=x86-64-v3, GCC's default contraction")
    common = {"date": today, "routine": "W3SNL1", "machine": machine(), "toolchain": toolchain,
              "commit": commit, "statistic": f"median of {a.runs} runs (one process each)",
              "regtest": a.regtest}
    if dirty:
        common["commit_note"] = f"working tree of {commit} with uncommitted changes when measured"

    def get(kind, case, t, v):
        for r in data:
            if (r["kind"], r["case"], r["threads"], r["variant"]) == (kind, case, t, v):
                return r["median"]
        return None

    kernel_runs = []
    for case in GRIDS:
        for t in sorted({r["threads"] for r in data if r["kind"] == "kernel"}, key=int):
            f = get("kernel", case, t, "fortran")
            if f is None:
                continue
            b, p, v1 = (get("kernel", case, t, v) for v in ("v2_batch", "v2_point", "v1"))
            kernel_runs.append({
                "backend": f"{label(t)}, {GRIDS[case]}",
                "command": f"env OMP_NUM_THREADS={t} build/bench-dia/driver/bench_dia {a.points} {a.calls} 3 "
                           f"(in build/bench-dia/runs/grid-{case}; scripts/bench_dia.sh)",
                "fortran_ms": float(f), "v2_batch_ms": float(b), "v2_point_ms": float(p), "v1_ms": float(v1),
                "v2_batch_vs_fortran": ratio(f, b), "v2_point_vs_fortran": ratio(f, p),
            })
    kernel = dict(common, study="dia-cpu-kernel", **{
        "what": (f"the DIA alone on {a.points} synthetic spectra per call, 3 warm-up + {a.calls} timed calls, ms per call: "
                 "WW3's W3SNL1 from libww3 (one call per point, !$OMP over points), the Kokkos port (v2) through "
                 "the shim in one call and once per point in a critical section as W3SRCE calls it, and "
                 "ww3-dia-gpu's kernel on the CPU (v1: SA1/SA2 of section 3 only, its own synthetic tables; "
                 "not the same work, docs/W3SNL1_GPU_COMPARISON_202610.md). v2's S and D equal the "
                 "Fortran's bit for bit on these inputs (the driver stops otherwise)."),
        "columns": [["backend, grid", "backend"], ["WW3 Fortran ms", "fortran_ms"], ["v2 one call ms", "v2_batch_ms"],
                    ["v2 per point ms", "v2_point_ms"], ["v1 (partial) ms", "v1_ms"],
                    ["Fortran / v2 one call", "v2_batch_vs_fortran"], ["Fortran / v2 per point", "v2_point_vs_fortran"]],
        "runs": kernel_runs})
    out = [(RESULTS / f"dia-cpu-kernel-{today}.json", kernel)]

    if a.kernel_only != "1":
        model_runs = []
        for case in GRIDS:
            for t in sorted({r["threads"] for r in data if r["kind"] == "model"}, key=int):
                f, k = get("model", case, t, "fortran"), get("model", case, t, "kokkos")
                if f is None:
                    continue
                model_runs.append({
                    "backend": f"{label(t)}, {case}",
                    "command": f"env OMP_NUM_THREADS={t} WW_KOKKOS_SNL1=0|1 build/bench-dia/ww3/bin/ww3_shel "
                               f"(in build/bench-dia/runs/model-{case}-*; scripts/bench_dia.sh)",
                    "fortran_s": float(f), "kokkos_s": float(k), "fortran_vs_kokkos": ratio(f, k),
                })
        model = dict(common, study="dia-cpu-model", **{
            "what": ("ww3_shel wall time, one executable with the OMPG and KOKKOS switches, the Fortran DIA "
                     "(WW_KOKKOS_SNL1=0) against the Kokkos DIA (=1); v1 is not in WW3 and has no row"),
            "columns": [["backend, case", "backend"], ["WW3 Fortran DIA s", "fortran_s"],
                        ["Kokkos DIA s", "kokkos_s"], ["Fortran / Kokkos", "fortran_vs_kokkos"]],
            "runs": model_runs})
        out.append((RESULTS / f"dia-cpu-model-{today}.json", model))

    for path, rec in out:
        path.write_text(json.dumps(rec, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"bench_dia_record: {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
