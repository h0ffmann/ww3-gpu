#!/usr/bin/env python3
"""Measured results as data: bench/results/*.json -> the tables that quote them.

A record holds one study's runs with the machine, toolchain, statistic, L1 status and the command
of every run (bench/README.md: a row may only claim what a command reproduces). A Markdown page
quotes a study between `<!-- results:<study>:start -->` and `<!-- results:<study>:end -->`; the
table there is generated, so it cannot drift from the record.

    scripts/results.py table   # rewrite every marked table from the records
    scripts/results.py check   # CI: records valid, every timing has a passed L1, tables current
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
RESULTS = ROOT / "bench" / "results"
SKIP = {"WW3", "WW4", "nix-config", ".git", "build"}
REQUIRED = ("study", "date", "routine", "what", "machine", "toolchain", "l1", "statistic", "runs")
RUN_REQUIRED = ("backend", "command", "shim_ms", "kernel_ms")
HEADER = ["backend", "shim ms/call", "kernel ms/call", "points/s (shim)", "speed-up vs. Serial"]
BLOCK = re.compile(r"(<!-- results:([\w.-]+):start -->\n).*?(<!-- results:\2:end -->)", re.S)


def load(results=RESULTS):
    return {p: json.loads(p.read_text(encoding="utf-8")) for p in sorted(results.glob("*.json"))}


def problems(records):
    errs, studies = [], {}
    for path, r in records.items():
        name = path.name
        errs += [f"{name}: missing '{k}'" for k in REQUIRED if k not in r]
        for i, run in enumerate(r.get("runs", [])):
            errs += [f"{name}: run {i} missing '{k}'" for k in RUN_REQUIRED if k not in run]
        # AGENTS.md, "No timing without parity": a timing enters only after L1 passed on its build.
        if not str(r.get("l1", "")).startswith("passed"):
            errs.append(f"{name}: l1 is not 'passed: ...'; a timing without parity cannot be recorded")
        if r.get("commit") is None and not r.get("commit_note"):
            errs.append(f"{name}: no commit and no commit_note saying why")
        if r.get("study") in studies:
            errs.append(f"{name}: study '{r['study']}' also in {studies[r['study']]}")
        studies[r.get("study")] = name
    return errs


def table(record, source):
    rows = ["| " + " | ".join(HEADER) + " |", "|" + "---|" * len(HEADER)]
    for run in record["runs"]:
        cells = [run["backend"], f"{run['shim_ms']:g}", f"{run['kernel_ms']:g}",
                 run.get("points_per_s", "—"), run.get("speedup", "—")]
        rows.append("| " + " | ".join(cells) + " |")
    rows.append("")
    rows.append(f"<sub>Generated by `scripts/results.py` from [`{source}`]({source}); "
                f"edit the record, not this table.</sub>")
    return "\n".join(rows) + "\n"


def pages(root=ROOT):
    for p in sorted(root.rglob("*.md")):
        if not SKIP.intersection(p.relative_to(root).parts) and "<!-- results:" in p.read_text(encoding="utf-8"):
            yield p


def render(page, records, root=ROOT):
    by_study = {r["study"]: (p, r) for p, r in records.items()}
    text, missing = page.read_text(encoding="utf-8"), []

    def sub(m):
        if m.group(2) not in by_study:
            missing.append(m.group(2))
            return m.group(0)
        path, record = by_study[m.group(2)]
        rel = pathlib.Path(*[".."] * (len(page.relative_to(root).parts) - 1), path.relative_to(root))
        return m.group(1) + table(record, rel.as_posix()) + m.group(3)

    return BLOCK.sub(sub, text), missing


def main(argv):
    cmd = argv[0] if argv else "check"
    records = load()
    errs = problems(records)
    for page in pages():
        new, missing = render(page, records)
        errs += [f"{page.relative_to(ROOT)}: no record for study '{s}'" for s in missing]
        if cmd == "table":
            page.write_text(new, encoding="utf-8")
        elif new != page.read_text(encoding="utf-8"):
            errs.append(f"{page.relative_to(ROOT)}: table is stale; run `python3 scripts/results.py table`")
    for e in errs:
        print(e, file=sys.stderr)
    if not errs:
        print(f"results: {len(records)} record(s), tables current")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
