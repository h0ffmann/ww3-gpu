#!/usr/bin/env python3
"""Measured results as data: bench/results/*.json -> the tables that quote them.

A record holds one study's runs with the machine, toolchain, statistic, the WW3 regtest replay that
passed on the same commit (`regtest`) and the command of every run (bench/README.md: a row may only claim what a command reproduces). A Markdown page
quotes a study between `<!-- results:<study>:start -->` and `<!-- results:<study>:end -->`; the
table there is generated, so it cannot drift from the record.

    scripts/results.py table   # rewrite every marked table from the records
    scripts/results.py check   # CI: records valid, every timing has a passed regtest, tables current
    scripts/results.py record <perf.tsv>   # the record of a `ww3-gpu.sh --repeat N` run (N >= 3)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
RESULTS = ROOT / "bench" / "results"
SKIP = {"WW3", "WW4", "picasso", ".git", "build"}
REQUIRED = ("study", "date", "routine", "what", "machine", "toolchain", "statistic", "runs")
# ADR-0010: from this date parity is a passed WW3 regtest replay; a record dated before it kept
# the L1 test of its day (`l1`) and stays valid as history.
REGTEST_SINCE = "2026-10-14"
RUN_REQUIRED = ("backend", "command", "shim_ms", "kernel_ms")
HEADER = ["backend", "shim ms/call", "kernel ms/call", "points/s (shim)", "speed-up vs. Serial"]
BLOCK = re.compile(r"(<!-- results:([\w.-]+):start -->\n).*?(<!-- results:\2:end -->)", re.S)


def load(results=RESULTS):
    return {p: json.loads(p.read_text(encoding="utf-8")) for p in sorted(results.glob("*.json"))}


def problems(records):
    errs, studies = [], {}
    for path, r in records.items():
        name = path.name
        errs += [f"{name}: missing '{k}'" for k in REQUIRED if k not in r]
        need = run_required(r)
        for i, run in enumerate(r.get("runs", [])):
            errs += [f"{name}: run {i} missing '{k}'" for k in need if k not in run]
        # AGENTS.md, "No timing without parity": a timing enters only after a WW3 regtest replay
        # passed on the same commit.
        parity = r.get("regtest")
        if parity is None and str(r.get("date", "")) < REGTEST_SINCE:
            parity = r.get("l1")
        if not str(parity or "").startswith("passed"):
            errs.append(f"{name}: regtest is not 'passed: <command>'; a timing without parity cannot be recorded")
        if r.get("commit") is None and not r.get("commit_note"):
            errs.append(f"{name}: no commit and no commit_note saying why")
        if r.get("study") in studies:
            errs.append(f"{name}: study '{r['study']}' also in {studies[r['study']]}")
        studies[r.get("study")] = name
    return errs


def run_required(record):
    """A record with `columns` ([[header, key], ...]) needs those keys and a command per run."""
    if "columns" in record:
        return ("backend", "command") + tuple(k for _, k in record["columns"] if k != "backend")
    return RUN_REQUIRED


def cell(v):
    return f"{v:g}" if isinstance(v, (int, float)) else str(v)


def table(record, source):
    if "columns" in record:
        cols = record["columns"]
        rows = ["| " + " | ".join(h for h, _ in cols) + " |", "|" + "---|" * len(cols)]
        for run in record["runs"]:
            rows.append("| " + " | ".join(cell(run.get(k, "—")) for _, k in cols) + " |")
    else:
        rows = ["| " + " | ".join(HEADER) + " |", "|" + "---|" * len(HEADER)]
        for run in record["runs"]:
            cells = [run["backend"], f"{run['shim_ms']:g}", f"{run['kernel_ms']:g}",
                     run.get("points_per_s", "—"), run.get("speedup", "—")]
            rows.append("| " + " | ".join(cells) + " |")
    rows.append("")
    rows.append(f"<sub>Generated by `scripts/results.py` from [`{source}`]({source}); "
                f"edit the record, not this table.</sub>")
    return "\n".join(rows) + "\n"


def pages(root=ROOT):
    for p in sorted(root.rglob("*.md")):
        if not SKIP.intersection(p.relative_to(root).parts) and "<!-- results:" in p.read_text(encoding="utf-8"):
            yield p


def render(page, records, root=ROOT):
    by_study = {r["study"]: (p, r) for p, r in records.items()}
    text, missing = page.read_text(encoding="utf-8"), []

    def sub(m):
        if m.group(2) not in by_study:
            missing.append(m.group(2))
            return m.group(0)
        path, record = by_study[m.group(2)]
        rel = pathlib.Path(*[".."] * (len(page.relative_to(root).parts) - 1), path.relative_to(root))
        return m.group(1) + table(record, rel.as_posix()) + m.group(3)

    return BLOCK.sub(sub, text), missing


def from_perf(perf):
    """The record of one `scripts/ww3-gpu.sh --ww3-gpu <case> --repeat N` run, from the perf.tsv it
    writes after its parity checks passed (pure WW3 against ww3-gpu, the same switch, alternated)."""
    kv = dict(line.split("\t", 1) for line in perf.read_text(encoding="utf-8").splitlines() if "\t" in line)
    n = int(kv["repeat"])
    if n < 3:
        raise ValueError(f"{perf}: {n} runs; a timing for a table is the median of three or more (bench/README.md)")
    m3, m1 = float(kv["ww3_median_s"]), float(kv["ww3gpu_median_s"])
    model = re.sub(r"\s*\(UUID:[^)]*\)", "", kv.get("gpu", "")).strip()  # never the card's UUID
    gpu = f" + {model}, driver {kv['driver']}" if model else ""
    record = {
        "study": f"ww3-vs-ww3gpu-{kv['case']}-{kv['backend']}-{kv['date']}",
        "date": kv["date"],
        "routine": f"WW3 end to end (ww3_shel): pure NOAA WW3 against ww3-gpu with {kv['parts']}",
        "what": (f"ww3_shel wall time, case {kv['case']}, {kv['switch']}: --ww3 is NOAA WW3 from WW3-noaa/, "
                 f"--ww3-gpu the fork with those parts on Kokkos {kv['backend']} and the rest in Fortran; "
                 f"{n} runs of each, alternated, every output byte-identical to run 1's"),
        "machine": f"{kv['cpu']} ({kv['threads']} hardware threads){gpu}",
        "toolchain": "; ".join(x for x in (kv.get("toolchain"), kv.get("kokkos")) if x),
        "commit": kv["commit"] or None,
        "ww3_commit": kv["ww3_commit"],
        "regtest": (f"passed: {kv['command']} (nccmp-tol PASS against the Fortran of the same executable "
                    f"and against --ww3, before the timed runs)"),
        "statistic": f"median of {n} runs",
        "columns": [["build", "backend"], ["ww3_shel median (s)", "median_s"], ["runs (s)", "runs_s"],
                    ["--ww3 median / this median", "ratio"]],
        "runs": [
            {"backend": f"--ww3, pure NOAA WW3 ({kv['baseline']})", "command": kv["command"],
             "median_s": m3, "runs_s": kv["ww3_s"], "ratio": "1.00x"},
            {"backend": f"--ww3-gpu, {kv['parts']} on {kv['backend']}", "command": kv["command"],
             "median_s": m1, "runs_s": kv["ww3gpu_s"], "ratio": f"{m3 / m1:.2f}x"},
        ],
    }
    if kv.get("dirty"):
        record["commit_note"] = "the tree had uncommitted changes when it ran; the commit is its parent"
    if not record["commit"]:
        record["commit_note"] = "the run did not know its commit (no git, no BUILD_INFO)"
    return record


def record_cmd(perf, results=RESULTS):
    r = from_perf(pathlib.Path(perf))
    # The name comes from the file's fields: a study is a plain file name, never a path.
    if not re.fullmatch(r"[a-z0-9][a-z0-9.-]*", r["study"]):
        raise ValueError(f"{perf}: study name {r['study']!r} is not a plain file name")
    out = results / f"{r['study']}.json"
    if out.exists():
        raise FileExistsError(f"{out} exists; a record is not overwritten")
    out.write_text(json.dumps(r, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"results: wrote {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}")
    return 0


def main(argv):
    cmd = argv[0] if argv else "check"
    if cmd == "record":
        if len(argv) != 2:
            print("results: record <perf.tsv>", file=sys.stderr)
            return 64
        try:
            return record_cmd(argv[1])
        except (ValueError, KeyError, FileExistsError, OSError) as e:
            print(f"results: {e}", file=sys.stderr)
            return 1
    records = load()
    errs = problems(records)
    for page in pages():
        new, missing = render(page, records)
        errs += [f"{page.relative_to(ROOT)}: no record for study '{s}'" for s in missing]
        if cmd == "table":
            page.write_text(new, encoding="utf-8")
        elif new != page.read_text(encoding="utf-8"):
            errs.append(f"{page.relative_to(ROOT)}: table is stale; run `python3 scripts/results.py table`")
    for e in errs:
        print(e, file=sys.stderr)
    if not errs:
        print(f"results: {len(records)} record(s), tables current")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
