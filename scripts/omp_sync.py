#!/usr/bin/env python3
"""Generate the Oh My Pi (omp) files that cannot be read from the Claude Code setup directly.

omp reads AGENTS.md, .claude/skills, .claude/commands and .mcp.json as they are. Two inputs it
does not take from them, so they are generated here and committed (CONTRIBUTING.md, "Working with
Oh My Pi"):

- .omp/agents/<name>.md from .claude/agents/<name>.md: omp skips .claude/agents because their
  front matter is Claude Code's. The `model` key is dropped, as omp does for Claude-dialect plugin
  agents, so a Claude alias such as `opus` is not read as an omp model selector.
- .omp/RULES.md: task subagents drop every context file named AGENTS.md but keep RULES.md, so the
  repo invariants and the GPU rule of AGENTS.md reach them from here, with links flattened to text.

    python3 scripts/omp_sync.py --write      # regenerate
    python3 scripts/omp_sync.py --check      # exit 1 when a generated file is stale (CI)
    python3 scripts/omp_sync.py --self-test
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED = "generated by scripts/omp_sync.py from {src}; edit that file, then --write"


def section(text: str, heading: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## )", text, re.S | re.M)
    if not m:
        raise SystemExit(f"omp_sync: AGENTS.md has no section '## {heading}'")
    return m.group(1).strip()


def first_bullet(body: str) -> str:
    m = re.search(r"^- .*?(?=^- |\Z)", body, re.S | re.M)
    if not m:
        raise SystemExit("omp_sync: no bullet found")
    return m.group(0).strip()


def flatten_links(text: str) -> str:
    # RULES.md lives in .omp/, where the relative links of AGENTS.md would not resolve.
    text = re.sub(r"\[([^\]]+)\]\(#[^)]+\)", r'AGENTS.md, "\1"', text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    return re.sub(r"^<!--.*?-->\n?", "", text, flags=re.M)


def rules(agents_md: str) -> str:
    invariants = section(agents_md, "Repo invariants").split("\n\n", 1)[1]
    gpu = first_bullet(section(agents_md, "Running on the GPU (hard rule)"))
    return (
        f"<!-- {GENERATED.format(src='AGENTS.md')} -->\n"
        "# ww3-gpu: rules that hold in every session and subagent\n\n"
        "The full rulebook is `AGENTS.md` at the repository root; where this list and it differ,\n"
        "`AGENTS.md` wins.\n\n"
        f"{flatten_links(invariants)}\n{flatten_links(gpu)}\n"
    )


def agent(text: str, src: str) -> str:
    parts = text.split("---\n", 2)
    if len(parts) != 3 or parts[0]:
        raise SystemExit(f"omp_sync: {src} has no front matter")
    front = [line for line in parts[1].splitlines() if not line.startswith("model:")]
    return "---\n" + "\n".join([f"# {GENERATED.format(src=src)}", *front]) + "\n---\n" + parts[2]


def expected() -> dict:
    out = {ROOT / ".omp/RULES.md": rules((ROOT / "AGENTS.md").read_text(encoding="utf-8"))}
    for src in sorted((ROOT / ".claude/agents").glob("*.md")):
        out[ROOT / ".omp/agents" / src.name] = agent(src.read_text(encoding="utf-8"), str(src.relative_to(ROOT)))
    return out


def stale() -> list:
    want = expected()
    bad = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    bad += [p for p in (ROOT / ".omp/agents").glob("*.md") if p not in want]
    return sorted(bad)


def self_test() -> int:
    md = (
        "## Repo invariants\n\nintro.\n\n- **A** ([x](#a-hard-rule)).\n- **B** ([ADR](docs/a.md)).\n<!-- end -->\n"
        "## Running on the GPU (hard rule)\n\nquote.\n\n- **Never** gpu.\n  more.\n- **Other**.\n## End\n"
    )
    r = rules(md)
    assert '- **A** (AGENTS.md, "x").' in r, r
    assert "- **B** (ADR)." in r, r
    assert "<!-- end" not in r and "- **Never** gpu.\n  more." in r and "Other" not in r and "intro" not in r, r
    a = agent("---\nname: x\ndescription: \"d\"\ntools: Read, Grep\nmodel: opus\n---\n\nbody\n", "src.md")
    assert a.startswith("---\n# generated by scripts/omp_sync.py from src.md") and "model:" not in a, a
    assert a.endswith('description: "d"\ntools: Read, Grep\n---\n\nbody\n'), a
    expected()  # the real AGENTS.md and agents still parse
    print("omp_sync self-test ok")
    return 0


def main(argv: list) -> int:
    if argv == ["--self-test"]:
        return self_test()
    if argv == ["--write"]:
        (ROOT / ".omp/agents").mkdir(parents=True, exist_ok=True)
        want = expected()
        for p in (ROOT / ".omp/agents").glob("*.md"):
            if p not in want:
                p.unlink()
        for p, text in want.items():
            p.write_text(text, encoding="utf-8")
        print(f"omp_sync: wrote {len(want)} files")
        return 0
    if argv == ["--check"]:
        bad = stale()
        for p in bad:
            print(f"omp_sync: stale {p.relative_to(ROOT)} (python3 scripts/omp_sync.py --write)")
        return 1 if bad else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
