/// Result of DIAGONALIZE: NROT, and whether the 50 sweeps ran out (the Fortran then writes
/// 'Too many iterations in DIAGONALIZE' to unit 6 and returns what it has).
struct DiagonalizeResult {
  int nrot = 0;
  bool too_many_iterations = false;
};

/// DIAGONALIZE(A1, D, V, NROT) (w3servmd.F90:2308-2387), Jacobi eigenvalues and vectors of the
/// symmetric n x n matrix a1 (column-major, a1(i,j) at i + n*j, only the upper triangle is
/// read). d (n) and v (n x n, column-major) are outputs. The Fortran's size(D) is n.
inline DiagonalizeResult diagonalize(int n, const double* a1, double* d, double* v) {
  DiagonalizeResult res;
  std::vector<double> a(a1, a1 + static_cast<std::size_t>(n) * static_cast<std::size_t>(n));
  std::vector<double> b(static_cast<std::size_t>(n)), z(static_cast<std::size_t>(n), 0.0);
  auto A = [&](int i, int j) -> double& {
    return a[static_cast<std::size_t>(i) + static_cast<std::size_t>(n) * static_cast<std::size_t>(j)];
  };
  auto V = [&](int i, int j) -> double& {
    return v[static_cast<std::size_t>(i) + static_cast<std::size_t>(n) * static_cast<std::size_t>(j)];
  };
  for (int k = 0; k < n * n; ++k) v[k] = 0.0;
  for (int i = 0; i < n; ++i) {
    V(i, i) = 1.0;
    b[static_cast<std::size_t>(i)] = A(i, i);
  }
  for (int i = 0; i < n; ++i) d[i] = b[static_cast<std::size_t>(i)];
  int nrot = 0;
  // s and tau are the host variables ROTATE reads.
  double s = 0.0, tau = 0.0;
  auto rotate = [&](double& x1, double& x2) {
    const double mem = x1;
    x1 = x1 - s * (x2 + x1 * tau);
    x2 = x2 + s * (mem - x2 * tau);
  };
  for (int it = 1; it <= 50; ++it) {
    double sm = 0.0;  // SUM(ABS(A), MASK=UPPER_TRIANGLE), column-major order
    for (int j = 0; j < n; ++j) {
      for (int i = 0; i < j; ++i) sm = sm + std::fabs(A(i, j));
    }
    if (sm == 0.0) {
      res.nrot = nrot;
      return res;
    }
    // MERGE(0.2*SM/N**2, 0.D0, I<4); 0.2 is a REAL literal.
    const double tresh = (it < 4) ? ((static_cast<double>(0.2f) * sm) / static_cast<double>(n * n)) : 0.0;
    for (int ip = 1; ip <= n - 1; ++ip) {
      for (int iq = ip + 1; iq <= n; ++iq) {
        const int p0 = ip - 1;
        const int q0 = iq - 1;
        const double g = 100.0 * std::fabs(A(p0, q0));
        const double dp = d[p0];
        const double dq = d[q0];
        if ((it > 4) && (std::fabs(dp) + g == std::fabs(dp)) && (std::fabs(dq) + g == std::fabs(dq))) {
          A(p0, q0) = 0.0;
        } else if (std::fabs(A(p0, q0)) > tresh) {
          double h = dq - dp;
          double t;
          if (std::fabs(h) + g == std::fabs(h)) {
            t = A(p0, q0) / h;
          } else {
            const double theta = (h * 0.5) / A(p0, q0);
            t = 1.0 / (std::fabs(theta) + std::sqrt(1.0 + theta * theta));
            if (theta < 0.0) t = -t;
          }
          const double c = 1.0 / std::sqrt(1.0 + t * t);
          s = t * c;
          tau = s / (1.0 + c);
          h = t * A(p0, q0);
          z[static_cast<std::size_t>(p0)] = z[static_cast<std::size_t>(p0)] - h;
          z[static_cast<std::size_t>(q0)] = z[static_cast<std::size_t>(q0)] + h;
          d[p0] = d[p0] - h;
          d[q0] = d[q0] + h;
          A(p0, q0) = 0.0;
          for (int k = 0; k < p0; ++k) rotate(A(k, p0), A(k, q0));            // A(1:IP-1,IP), A(1:IP-1,IQ)
          for (int k = p0 + 1; k < q0; ++k) rotate(A(p0, k), A(k, q0));      // A(IP,IP+1:IQ-1), A(IP+1:IQ-1,IQ)
          for (int k = q0 + 1; k < n; ++k) rotate(A(p0, k), A(q0, k));       // A(IP,IQ+1:N), A(IQ,IQ+1:N)
          for (int k = 0; k < n; ++k) rotate(V(k, p0), V(k, q0));            // V(:,IP), V(:,IQ)
          nrot = nrot + 1;
        }
      }
    }
    for (int i = 0; i < n; ++i) {
      b[static_cast<std::size_t>(i)] = b[static_cast<std::size_t>(i)] + z[static_cast<std::size_t>(i)];
      d[i] = b[static_cast<std::size_t>(i)];
      z[static_cast<std::size_t>(i)] = 0.0;
    }
  }
  res.nrot = nrot;
  res.too_many_iterations = true;
  return res;
}

/// What INSIS2 reads of W3GDATMD: SIG(1:NK) (so &SIG(1) of SIG(0:NK+1)), IS2PARS(1:24),
/// EC2, ES2, ECOS (their first NTH elements).
struct Insis2Grid {
  int nk;
  int nth;
  const Real* sig;
  const Real* is2pars;
  const Real* ec2;
  const Real* es2;
  const Real* ecos;
};

/// The module variables INSIS2 allocates and fills (w3sis2md.F90:78-92). SIS2ALPHAS and
/// SIS2ALPHA2 are (NTHICK,NK), (j,i) at (j-1) + NTHICK*(i-1); IS2SCATMAT and IS2EIGVEC are
/// (NTH,NTH) column-major, IS2EIGVAL is (NTH).
struct Is2Tables {
  std::vector<Real> sis2alphas;
  std::vector<Real> sis2alpha2;
  std::array<Real, kNiced> icedavetab{};
  std::vector<double> is2scatmat;
  std::vector<double> is2eigvec;
  std::vector<double> is2eigval;
  DiagonalizeResult diag;
};

/// INSIS2 (:103-620). The test output and the commented WRITEs are not ported, nor
/// SIS1HTABLE, which is assigned and never read, nor ICEDMIN.
inline void insis2(const Insis2Grid& g, Is2Tables& t) {
  using namespace insis2_detail;
  const int nk = g.nk;
  const int nth = g.nth;
  constexpr int nftab = 25;
  const Real* ftab = kSis1FTable;
  const Real* tab = (g.is2pars[17] < 0.5f) ? kSis1AlphaTableA : kSis1AlphaTableB;
  const Real* tab2 = kSis1AlphaTable2;

  t.sis2alphas.assign(static_cast<std::size_t>(kNthick) * static_cast<std::size_t>(nk > 0 ? nk : 0), 0.0f);
  t.sis2alpha2.assign(t.sis2alphas.size(), 0.0f);

  auto interp = [&](const Real* table, std::vector<Real>& out) {
    for (int i = 1; i <= nk; ++i) {
      for (int j = 1; j <= kNthick; ++j) {
        const Real f = g.sig[i - 1] * ww::srce::kTpiInv;
        Real val;
        if (f < ftab[0]) {
          val = table[j - 1];
        } else if (f > ftab[nftab - 1]) {
          val = table[(j - 1) + kNthick * (nftab - 1)];
        } else {
          int ind = 1;
          for (int k = 1; k <= nftab - 1; ++k) {
            if (ftab[k - 1] < f) ind = k;
          }
          const Real x = ((f - ftab[ind - 1])) / ((ftab[ind] - ftab[ind - 1]));
          val = table[(j - 1) + kNthick * (ind - 1)] * ((1.0f - x)) +
                table[(j - 1) + kNthick * ind] * x;
        }
        out[static_cast<std::size_t>((j - 1) + kNthick * (i - 1))] = val;
      }
    }
  };
  interp(tab, t.sis2alphas);
  interp(tab2, t.sis2alpha2);

  // :581-583. The copy of W3FSD_DAVE inlined in INSIS2 has the MAX operands the other way.
  for (int i = 1; i <= kNiced; ++i) {
    t.icedavetab[static_cast<std::size_t>(i - 1)] =
        w3fsd_dave<true>(g.is2pars[8], static_cast<Real>(i), g.is2pars[7]);
  }

  // :588-603.
  const std::size_t nn = static_cast<std::size_t>(nth) * static_cast<std::size_t>(nth);
  t.is2scatmat.assign(nn, 0.0);
  t.is2eigvec.assign(nn, 0.0);
  t.is2eigval.assign(static_cast<std::size_t>(nth), 0.0);
  auto M = [&](int i, int j) -> double& {
    return t.is2scatmat[static_cast<std::size_t>(i - 1) + static_cast<std::size_t>(nth) * static_cast<std::size_t>(j - 1)];
  };
  const double inv = 1.0 / static_cast<double>(nth);  // 1./DBLE(NTH)
  for (int i = 1; i <= nth; ++i) {
    for (int j = 1; j <= nth; ++j) {
      const int k = (i > j ? i - j : j - i);  // ABS(I-J)
      const Real c2 = g.ec2[k];
      const Real co = g.ecos[k];
      const Real e = (c2 * c2) * 2.0f + ((co * co) * co) * 0.8f;
      M(i, j) = -(inv * static_cast<double>(e));
      if (co < 1.0E-3f) {
        M(i, j) = M(i, j) - (inv * static_cast<double>(0.8f)) * static_cast<double>(g.es2[k]);
      }
    }
    double sum = 0.0;  // SUM(IS2SCATMAT(I,1:NTH))
    for (int j = 1; j <= nth; ++j) sum = sum + M(i, j);
    M(i, i) = M(i, i) - sum;
  }
  t.diag = diagonalize(nth, t.is2scatmat.data(), t.is2eigval.data(), t.is2eigvec.data());
  // :605-607 MAX(0.D0, IS2EIGVAL(I)). The object takes pairs through maxpd (X > 0 ? X : 0) and
  // an odd last element through maxsd (0 > X ? 0 : X); they differ for NaN and -0 only.
  const int npair = nth / 2;
  for (int i = 0; i < 2 * npair; ++i) {
    double& x = t.is2eigval[static_cast<std::size_t>(i)];
    x = (x > 0.0) ? x : 0.0;
  }
  if (nth % 2 == 1) {
    double& x = t.is2eigval[static_cast<std::size_t>(nth - 1)];
    x = (0.0 > x) ? 0.0 : x;
  }
}

