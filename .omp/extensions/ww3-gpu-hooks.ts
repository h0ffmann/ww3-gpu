// The Claude Code hooks of .claude/settings.json, run from Oh My Pi (omp). omp does not execute
// Claude's command hooks, so this extension calls the same scripts with the JSON Claude Code would
// send and maps their answer back: one source for the rule, two harnesses. CONTRIBUTING.md,
// "Working with Oh My Pi", has the mapping and what is not carried over.
import { spawn } from "node:child_process";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import type { ExtensionAPI } from "@oh-my-pi/pi-coding-agent";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OMP_NOTE =
	'In omp the reviewer is the task tool with agent "revisor-proposta" (.omp/agents/, generated by scripts/omp_sync.py).';

function run(script: string, stdin: object): Promise<{ code: number; stdout: string; stderr: string }> {
	return new Promise(resolve => {
		const child = spawn("bash", [path.join(ROOT, script)], { cwd: ROOT });
		let stdout = "";
		let stderr = "";
		child.stdout.on("data", d => (stdout += d));
		child.stderr.on("data", d => (stderr += d));
		child.on("error", e => resolve({ code: -1, stdout, stderr: String(e) }));
		child.on("close", code => resolve({ code: code ?? -1, stdout, stderr }));
		child.stdin.end(JSON.stringify(stdin));
	});
}

export default function (pi: ExtensionAPI) {
	pi.setLabel("ww3-gpu hooks");

	// PostToolUse on Write|Edit: .claude/hooks/proposal-review.sh, a reminder, never a block.
	pi.on("tool_result", async event => {
		if (event.isError || !["write", "edit", "ast_edit"].includes(event.toolName)) return;
		const file = event.input.path ?? event.input.file_path;
		if (typeof file !== "string") return;
		const { stdout } = await run(".claude/hooks/proposal-review.sh", { tool_input: { file_path: file } });
		if (!stdout.trim()) return;
		try {
			const context = JSON.parse(stdout).hookSpecificOutput?.additionalContext;
			if (typeof context === "string") return { additionalContext: `${context}\n${OMP_NOTE}` };
		} catch {
			return { additionalContext: `.claude/hooks/proposal-review.sh printed non-JSON: ${stdout.slice(0, 200)}` };
		}
	});

	// Stop: .claude/hooks/proposal-review-stop.sh; its exit 2 refuses to end the session.
	pi.on("session_stop", async event => {
		const { code, stderr } = await run(".claude/hooks/proposal-review-stop.sh", {
			stop_hook_active: event.stop_hook_active,
		});
		if (code === 2) return { decision: "block", reason: `${stderr.trim()}\n\n${OMP_NOTE}` };
	});
}
